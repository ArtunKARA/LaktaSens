create schema if not exists core;

-- =========================
-- 1) BOLGE
-- =========================
create table if not exists core.bolge (
    bolge_id bigint generated by default as identity primary key,
    sehir_ilce_mahalle_adi text,
    ust_id bigint null,
    min_longitude text,
    min_latitude text,
    max_longitude text,
    max_latitude text,
    mahalle_id text,
    constraint fk_bolge_ust
        foreign key (ust_id) references core.bolge(bolge_id)
        on delete set null
);

create index if not exists ix_bolge_ust_id
    on core.bolge (ust_id);

-- =========================
-- 2) FIRMA
-- =========================
create table if not exists core.firma (
    firma_id bigint generated by default as identity primary key,
    firma_adi varchar(50),
    firma_tur char(1),
    telefon_no varchar(15),
    firma_mail varchar(50),
    firma_adresi varchar(250),
    sehir_id bigint not null,
    ilce_id bigint not null,
    bolge_kod char(1),
    hesap_durumu char(1),

    constraint fk_firma_sehir
        foreign key (sehir_id) references core.bolge(bolge_id),

    constraint fk_firma_ilce
        foreign key (ilce_id) references core.bolge(bolge_id),

    constraint ck_firma_tur
        check (firma_tur in ('c', 't')),

    constraint ck_firma_hesap_durumu
        check (hesap_durumu in ('a', 'p', 'b'))
);

create index if not exists ix_firma_sehir_id
    on core.firma (sehir_id);

create index if not exists ix_firma_ilce_id
    on core.firma (ilce_id);

-- =========================
-- 3) SAGIM MAKINE
-- =========================
create table if not exists core.sagim_makine (
    makine_id bigint generated by default as identity primary key,
    makine_ad varchar(50),
    hazne_hacmi double precision,
    qr varchar(50),
    firma_id bigint,

    constraint fk_sagim_makine_firma
        foreign key (firma_id) references core.firma(firma_id)
        on delete set null
);

create index if not exists ix_sagim_makine_firma_id
    on core.sagim_makine (firma_id);

create unique index if not exists ux_sagim_makine_qr
    on core.sagim_makine (qr)
    where qr is not null;

-- =========================
-- 4) INEK
-- =========================
create table if not exists core.inek (
    inek_id bigint generated by default as identity primary key,
    inek_qr varchar(50) unique,
    ad varchar(20),
    irk varchar(20),
    kilo double precision,
    dogum_tarihi date,
    son_dogurma_tarihi date,
    firma_id bigint,
    anne_id bigint null,
    son_dollenme_tarihi date,
    dollenme_sayisi integer,
    tuttu_mu char(1),
    son_kuru_tarihi date,
    son_sut_olcum_tarihi date,

    constraint fk_inek_firma
        foreign key (firma_id) references core.firma(firma_id)
        on delete set null,

    constraint fk_inek_anne
        foreign key (anne_id) references core.inek(inek_id)
        on delete set null,

    constraint ck_inek_tuttu_mu
        check (tuttu_mu in ('e', 'h') or tuttu_mu is null)
);

create index if not exists ix_inek_firma_id
    on core.inek (firma_id);

create index if not exists ix_inek_anne_id
    on core.inek (anne_id);

create index if not exists ix_inek_son_dogurma_tarihi
    on core.inek (son_dogurma_tarihi);

create index if not exists ix_inek_son_dollenme_tarihi
    on core.inek (son_dollenme_tarihi);

-- =========================
-- 5) SURUDEN CIKARMA
-- =========================
create table if not exists core.suruden_cikarma (
    cikarma_id bigint generated by default as identity primary key,
    inek_id bigint not null,
    cikarilma_tarihi date not null,
    cikarilma_sebebi varchar(255) not null,

    constraint fk_suruden_cikarma_inek
        foreign key (inek_id) references core.inek(inek_id)
        on delete cascade
);

create index if not exists ix_suruden_cikarma_inek_id
    on core.suruden_cikarma (inek_id);

create index if not exists ix_suruden_cikarma_tarih
    on core.suruden_cikarma (cikarilma_tarihi);

-- =========================
-- 6) DOGURMA
-- =========================
create table if not exists core.dogurma (
    dogurma_id bigint generated by default as identity primary key,
    dogurma_tarihi date,
    inek_id bigint,

    constraint fk_dogurma_inek
        foreign key (inek_id) references core.inek(inek_id)
        on delete set null
);

create index if not exists ix_dogurma_inek_id
    on core.dogurma (inek_id);

create index if not exists ix_dogurma_tarih
    on core.dogurma (dogurma_tarihi);

-- =========================
-- 7) DOLLENME
-- =========================
create table if not exists core.dollenme (
    dollenme_id bigint generated by default as identity primary key,
    dollenme_tarihi date,
    inek_id bigint,
    dollenme_sayisi integer,
    tuttu_mu char(1),

    constraint fk_dollenme_inek
        foreign key (inek_id) references core.inek(inek_id)
        on delete set null,

    constraint ck_dollenme_tuttu_mu
        check (tuttu_mu in ('e', 'h') or tuttu_mu is null)
);

create index if not exists ix_dollenme_inek_id
    on core.dollenme (inek_id);

create index if not exists ix_dollenme_tarih
    on core.dollenme (dollenme_tarihi);

-- =========================
-- 8) KURU
-- =========================
create table if not exists core.kuru (
    kuru_id bigint generated by default as identity primary key,
    kuru_baslangic_tarihi date,
    inek_id bigint,

    constraint fk_kuru_inek
        foreign key (inek_id) references core.inek(inek_id)
        on delete set null
);

create index if not exists ix_kuru_inek_id
    on core.kuru (inek_id);

create index if not exists ix_kuru_tarih
    on core.kuru (kuru_baslangic_tarihi);

-- =========================
-- 9) SUT OLCUM
-- =========================
create table if not exists core.sut_olcum (
    olcum_id bigint generated by default as identity primary key,
    makine_id bigint,
    sut_miktar double precision,
    inek_id bigint,
    sagim_tarihi date,

    constraint fk_sut_olcum_makine
        foreign key (makine_id) references core.sagim_makine(makine_id)
        on delete set null,

    constraint fk_sut_olcum_inek
        foreign key (inek_id) references core.inek(inek_id)
        on delete set null
);

create index if not exists ix_sut_olcum_inek_id
    on core.sut_olcum (inek_id);

create index if not exists ix_sut_olcum_makine_id
    on core.sut_olcum (makine_id);

create index if not exists ix_sut_olcum_tarih
    on core.sut_olcum (sagim_tarihi);

create index if not exists ix_sut_olcum_inek_tarih
    on core.sut_olcum (inek_id, sagim_tarihi);