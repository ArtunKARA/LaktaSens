    aciklama,
    aktif
)
values (
    $$voederbomen_nutritionalvalues$$,
    $$Voederbomen nutritional values$$,
    $$scraped_csv$$,
    $$voederbomen_nutritionalvalues_detail_rows.csv; voederbomen_nutritionalvalues_average_rows.csv$$,
