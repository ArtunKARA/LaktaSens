with pivoted as (
    select
        feed_name,
        max(feed_id_code) as feed_id_code,
        max(source_url) as source_url,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'DM, % as fed') as dry_matter_percent,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'CP, % DM') as cp_percent_dm,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'NDF, % DM') as ndf_percent_dm,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'Starch, % DM') as starch_percent_dm,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'Crude fat, % DM') as fat_percent_dm,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'Ca, % DM') as ca_percent_dm,
        max(nullif(value_text, '')::double precision) filter (where nutrient = 'P, % DM') as p_percent_dm,
        jsonb_agg(
            jsonb_build_object(
                'nutrient', nutrient,
                'value', nullif(value_text, '')::double precision,
                'mean', nullif(mean_text, '')::double precision,
                'sd', nullif(sd_text, '')::double precision,
                'n', nullif(n_text, '')::double precision
            )
            order by nutrient
        ) as nutrient_payload
    from ml_smart_feed.stg_nasem_19_1_long
    group by feed_name
)
insert into ml_smart_feed.raw_feed_ingredient (
    kaynak_id,
    external_feed_id,
    feed_name,
    feed_category,
    dry_matter_percent,
    cp_percent_dm,
    ndf_percent_dm,
    starch_percent_dm,
    fat_percent_dm,
    ca_percent_dm,
    p_percent_dm,
    raw_payload
)
select
    k.kaynak_id,
    p.feed_id_code,
    p.feed_name,
    case
        when p.feed_name ilike '%silage%' or p.feed_name ilike '%hay%' or p.feed_name ilike '%straw%' then 'forage'
        when p.feed_name ilike '%grain%' or p.feed_name ilike '%meal%' or p.feed_name ilike '%bran%' then 'concentrate'
        else 'other'
    end as feed_category,
    p.dry_matter_percent,
    p.cp_percent_dm,
    p.ndf_percent_dm,
    p.starch_percent_dm,
    p.fat_percent_dm,
    p.ca_percent_dm,
    p.p_percent_dm,
    jsonb_build_object(
        'source_table', 'TABLE 19-1',
        'source_url', p.source_url,
        'nutrients', p.nutrient_payload
    )
from pivoted p
join ml_smart_feed.meta_veri_kaynagi k on k.kaynak_kod = 'nasem_2021_ncbi';

with mineral_pivot as (
    select
        mineral_source,
        mineral_source_id,
        max(source_category) as source_category,
        max(source_url) as source_url,
        max(nullif(percent_dm, '')::double precision) filter (where mineral = 'Ca') as ca_percent_dm,
        max(nullif(percent_dm, '')::double precision) filter (where mineral = 'P') as p_percent_dm,
        max(nullif(percent_dm, '')::double precision) filter (where mineral = 'Mg') as mg_percent_dm,
        max(nullif(percent_dm, '')::double precision) filter (where mineral = 'K') as k_percent_dm,
        max(nullif(percent_dm, '')::double precision) filter (where mineral = 'Na') as na_percent_dm,
        jsonb_agg(
            jsonb_build_object(
                'mineral_role', mineral_role,
                'mineral', mineral,
                'percent_dm', nullif(percent_dm, '')::double precision,
                'absorption_coefficient', nullif(absorption_coefficient, '')::double precision
            )
            order by mineral_role
        ) as mineral_payload
    from ml_smart_feed.stg_nasem_19_3_long
    group by mineral_source, mineral_source_id
)
