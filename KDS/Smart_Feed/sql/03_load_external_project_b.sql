    feed_ingredient_id,
    price_date,
    price_per_kg_dm,
    currency_code,
    kaynak_id
)
select
    f.feed_ingredient_id,
    p.price_date,
    p.price_per_kg_dm,
    'TRY',
    k.kaynak_id
from price_final p
join ml_smart_feed.opt_feed_ingredient f on f.feed_code = p.feed_code
join ml_smart_feed.meta_veri_kaynagi k on k.kaynak_kod = 'turib_feed_commodities'
on conflict (feed_ingredient_id, price_date) do update
set
    price_per_kg_dm = excluded.price_per_kg_dm,
    currency_code = excluded.currency_code,
    kaynak_id = excluded.kaynak_id;
