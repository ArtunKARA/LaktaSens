   or ml_smart_feed.opt_milk_price.kaynak_id is null;

with raw_prices as (
    select
        case
            when upper(product_group) like 'ARPA%' or product_group like 'A%' then 'NRC16F8'
            when upper(product_group) like 'MISIR%' or product_group like 'M%' then 'NRC16F44'
            when upper(product_group) like 'BUGDAY%' or product_group like 'B%' then 'NRC16F170'
            else null
        end as feed_code,
        record_date::date as price_date,
        avg(coalesce(nullif(weighted_avg_price_try_per_kg, '')::numeric, nullif(price_close_try_per_kg, '')::numeric)) as price_try_per_kg_asfed
    from ml_smart_feed.stg_turib_feed_history
    where nullif(record_date, '') is not null
      and coalesce(nullif(weighted_avg_price_try_per_kg, ''), nullif(price_close_try_per_kg, '')) is not null
    group by 1, 2
    union all
    select
        case
            when upper(product_group) like 'ARPA%' or product_group like 'A%' then 'NRC16F8'
            when upper(product_group) like 'MISIR%' or product_group like 'M%' then 'NRC16F44'
            when upper(product_group) like 'BUGDAY%' or product_group like 'B%' then 'NRC16F170'
            else null
        end as feed_code,
        (snapshot_as_of::timestamptz at time zone 'UTC')::date as price_date,
        avg(nullif(price_try_per_kg, '')::numeric) as price_try_per_kg_asfed
    from ml_smart_feed.stg_turib_feed_snapshot
    where nullif(snapshot_as_of, '') is not null
      and nullif(price_try_per_kg, '') is not null
    group by 1, 2
),
dm as (
    select
        f.feed_code,
        max(n.dry_matter_percent) as dry_matter_percent
    from ml_smart_feed.opt_feed_ingredient f
    left join ml_smart_feed.opt_feed_nutrient_value n
        on n.feed_ingredient_id = f.feed_ingredient_id
    where f.feed_code in ('NRC16F8', 'NRC16F44', 'NRC16F170')
    group by f.feed_code
),
price_final as (
    select
        r.feed_code,
        r.price_date,
        avg(
            case
                when d.dry_matter_percent is not null and d.dry_matter_percent > 0
                    then r.price_try_per_kg_asfed / (d.dry_matter_percent / 100.0)
                else r.price_try_per_kg_asfed
            end
        )::numeric(12,4) as price_per_kg_dm
    from raw_prices r
    left join dm d on d.feed_code = r.feed_code
    where r.feed_code is not null
    group by r.feed_code, r.price_date
)
