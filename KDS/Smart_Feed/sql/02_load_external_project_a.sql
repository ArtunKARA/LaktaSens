/*
PostgreSQL / psql import script for Smart Feed Proje A.

Purpose:
- Load external animal-state data into ml_smart_feed raw tables.
- Proje A covers lactation/state understanding, milk/DMI prediction, sensor
  signals, environment signals, and health/risk early-warning inputs.

Run from repository root after:
  psql -d <db_name> -f KDS/Smart_Feed/sql/ml_smart_feed_create.sql
  psql -d <db_name> -f KDS/Smart_Feed/sql/01_seed_meta_veri_kaynagi.sql

Then:
  psql -d <db_name> -f KDS/Smart_Feed/sql/02_load_external_project_a.sql

Note:
- This file uses psql \copy, so paths are read by the client machine.
- Run it from c:/Users/VICTUS/Desktop/Tubitak/LaktaSens or adjust paths.
- Large MmCows IMMU and pressure folders are not loaded by default because
  they are about 11 GB. Keep those as a separate high-frequency ETL step.
*/

\set ON_ERROR_STOP on

create table if not exists ml_smart_feed.raw_external_reference (
    raw_external_reference_id bigint generated by default as identity primary key,
    kaynak_id bigint not null references ml_smart_feed.meta_veri_kaynagi(kaynak_id),
    project_code text not null check (project_code in ('A', 'B', 'A_B')),
    reference_type text not null,
    artifact_name text not null,
    source_row_key text null,
    raw_payload jsonb not null,
    loaded_at timestamp not null default now()
);

create index if not exists ix_raw_external_reference_source
    on ml_smart_feed.raw_external_reference (kaynak_id, project_code, reference_type);

