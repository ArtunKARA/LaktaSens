/*
===============================================================================
ŞEMA: ml_smart_feed
AMAÇ:
- Bu şema, LaktaSens operasyonel core yapısını bozmadan laktasyon durumuna göre
  besleme ihtiyacı tahmini, sağlık/metabolik risk analizi ve yem/rasyon
  optimizasyonu için eğitim/simülasyon katmanı sağlar.
- Canlı operasyon tabloları üzerinde doğrudan ML/optimizasyon yapılmaz.
- Bu yapı araştırma, POC, model eğitimi, simülasyon ve karar destek hazırlığı
  için tasarlanmıştır.

PROJE AYRIMI:
- Proje A: Laktasyon evresi, besleme ihtiyacı, süt performansı ve sağlık/metabolik
  risk tahmini.
- Proje B: Proje A çıktıları ile yem/rasyon optimizasyonu, maliyet-verim-risk
  dengesi ve policy/simülasyon çıktıları.

GENEL TASARIM PRENSİPLERİ:
1) Bu şema core şemasını değiştirmez; core ile bağlar mapping alanları üzerinden kurulur.
2) Dış veriler önce raw_* tablolarında ham ve kayıpsız tutulur.
3) Farklı kaynaklardaki kimlik, birim, olay tipi ve yem adları map_* tabloları ile standartlaştırılır.
4) Modellemeye uygun temiz veriler norm_* tablolarında tutulur.
5) Proje A eğitim verileri ve tahmin çıktıları feat_* tablolarında tutulur.
6) Proje B yem, fiyat, rasyon ve optimizasyon çıktıları opt_* tablolarında tutulur.
7) Simülasyon, MDP/RL veya policy çıktıları sim_* tablolarında tutulur.
8) İsimlendirme ASCII uyumludur; tablo/kolon adlarında Türkçe karakter kullanılmaz.
9) Finansal alanlarda numeric, ölçüm alanlarında double precision tercih edilmiştir.
10) Ham veri tablolarında raw_payload jsonb alanı bırakılmıştır.
11) İlk sürümde trigger kullanılmaz; veri ETL/pipeline ile üretilir.

TABLO GRUPLARI:
- meta_* : veri kaynağı, deney koşusu ve senaryo takibi
- raw_*  : ham dış veri tabloları
- map_*  : dış veri / core / standart değer eşleme tabloları
- norm_* : normalize edilmiş günlük ve olay bazlı veri
- feat_* : Proje A feature, snapshot, label ve tahmin tabloları
- opt_*  : Proje B yem, ekonomik parametre, rasyon ve skor tabloları
- sim_*  : state, action, transition, reward ve policy çıktıları
===============================================================================
*/

create schema if not exists ml_smart_feed;

