/*
meta_veri_kaynagi
- Dış veri kaynaklarını ve manuel yüklemeleri tanımlar.
- Örnek: external_csv, lakta_core_export, feed_lab_excel, manual_upload.
- Proje A ve Proje B tarafından ortak kullanılır.
*/
create table if not exists ml_smart_feed.meta_veri_kaynagi (
    kaynak_id bigint generated by default as identity primary key,
    kaynak_kod text not null unique,
    kaynak_adi text not null,
    kaynak_tip text null,              -- csv, excel, api, core_export, manual
    dosya_adi text null,
    aciklama text null,
    aktif boolean not null default true,
    created_at timestamp not null default now()
);

/*
meta_experiment_run
- Model eğitimi, optimizasyon ve simülasyon koşularını takip eder.
- Proje A model denemeleri ve Proje B optimizer/simülasyon denemeleri burada izlenir.
*/
create table if not exists ml_smart_feed.meta_experiment_run (
    run_id bigint generated by default as identity primary key,
    run_kodu text not null unique,
    run_tipi text not null,            -- project_a_model, optimizer, simulation, mdp, baseline
    proje_kodu text not null check (proje_kodu in ('A', 'B', 'A_B')),
    model_adi text null,
    aciklama text null,
    parametre_json jsonb null,
    baslama_zamani timestamp not null default now(),
    bitis_zamani timestamp null,
    durum text not null default 'created'
        check (durum in ('created', 'running', 'completed', 'failed'))
);

/*
meta_senaryo
- Farklı yem fiyatı, süt fiyatı, risk cezası ve optimizasyon senaryolarını tanımlar.
- Özellikle Proje B için kullanılır; Proje A çıktılarının hangi senaryo ile çalıştırıldığını da izleyebilir.
*/
create table if not exists ml_smart_feed.meta_senaryo (
    senaryo_id bigint generated by default as identity primary key,
    senaryo_kodu text not null unique,
    senaryo_adi text not null,
    senaryo_tipi text null,            -- baseline, low_cost, balanced, risk_averse, high_yield
    aciklama text null,
    parametre_json jsonb null,
    aktif boolean not null default true,
    created_at timestamp not null default now()
);

