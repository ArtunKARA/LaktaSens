/*
===============================================================================
ŞEMA: suru_karar
AMAÇ:
- Bu şema, süt sığırcılığı işletmelerinde inek bazlı "elde tut / sürüden çıkar"
  kararları için RL tabanlı prototip geliştirme amacıyla tasarlanmıştır.
- Canlı sistem entegrasyonu YOKTUR.
- Bu yapı araştırma/prototip ortamı içindir.
- İleride gerçek uygulama şemasına taşınabilecek şekilde düzenli tutulmuştur.

GENEL TASARIM PRENSİPLERİ:
1) Bu şema tek başına çalışır; başka bir "core" şemaya bağımlı değildir.
2) Hafif master tablolar içerir:
   - master_inek
   - master_sagim_makine
3) Ham dış veriler doğrudan raw_* tablolarına alınır.
4) Temizlenmiş / normalize edilmiş olaylar event_* tablolarında tutulur.
5) Özellik/snapshot tabloları feat_* ile başlar.
6) RL geçiş ve politika çıktıları rl_* ile başlar.
7) İsimlendirme ASCII uyumludur; Türkçe karakter kullanılmaz.
8) Prototip esnekliği için:
   - durum ve tip alanlarında çoğunlukla text + check yaklaşımı kullanılmıştır.
   - ham veri tablolarında raw_payload jsonb alanları eklenmiştir.
9) Finansal alanlarda numeric, ölçüm alanlarında double precision tercih edilmiştir.
10) Gelecekte gerçek sisteme taşınma kolaylığı için tablo isimleri ve olay yapısı
    domain mantığına yakın tutulmuştur.
11) Bu prototipte firma / tenant / multi-farm katmanı BİLİNÇLİ OLARAK
    kapsam dışı bırakılmıştır. Karar birimi doğrudan "inek"tir.

TABLO GRUPLARI:
- meta_*   : veri kaynakları ve deney koşuları
- master_* : hafif ana varlık tabloları
- raw_*    : ham dış veri tabloları
- map_*    : dış kimlik eşleme tabloları
- event_*  : normalize edilmiş olay tabloları
- feat_*   : feature/snapshot ve RL giriş tabloları
- rl_*     : öğrenilen politika / değer çıktıları

NOT:
- Bu DDL "nihai prototip başlangıç şemasıdır".
- İlk sürümde trigger kullanılmaz; ETL/pipeline ile yükleme yapılır.
===============================================================================
*/

create schema if not exists suru_karar;

-- =============================================================================
-- META TABLOLARI
-- =============================================================================

/*
meta_veri_kaynagi
- Sisteme yüklenen dış veri kaynaklarını tanımlar.
- Örnek: corvasg, embryo_losses, inrae, manual_upload
*/
create table if not exists suru_karar.meta_veri_kaynagi (
    kaynak_id bigint generated by default as identity primary key,
    kaynak_kod text not null unique,
    kaynak_adi text not null,
    kaynak_tip text null,              -- excel, csv, api, manual
    aciklama text null,
    aktif boolean not null default true,
    created_at timestamp not null default now()
);

/*
meta_experiment_run
- Çalıştırılan deneyleri, veri seti versiyonlarını ve parametreleri izlemek için.
- RL / baseline ML / feature denemeleri burada takip edilir.
*/
create table if not exists suru_karar.meta_experiment_run (
    run_id bigint generated by default as identity primary key,
    run_kodu text not null unique,
    run_tipi text not null,            -- baseline_ml, mdp, offline_rl, simulation
    aciklama text null,
    parametre_json jsonb null,
    baslama_zamani timestamp not null default now(),
    bitis_zamani timestamp null,
    durum text not null default 'created'
        check (durum in ('created', 'running', 'completed', 'failed'))
);

