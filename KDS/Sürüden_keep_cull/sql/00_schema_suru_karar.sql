/*
master_inek
- Prototip için hayvan ana tablosu.
- Canlı sisteme taşınabilir olacak şekilde düzenli tutulmuştur.
- anne_id self-reference olarak tutulur.
- Bu prototipte firma bağı YOKTUR.
*/
create table if not exists suru_karar.master_inek (
    inek_id bigint generated by default as identity primary key,
    external_animal_id text null unique,
    inek_qr varchar(50) null unique,
    ad varchar(50) null,
    irk varchar(50) null,
    kilo double precision null,
    dogum_tarihi date null,
    son_dogurma_tarihi date null,
    anne_id bigint null references suru_karar.master_inek(inek_id) on delete set null,
    son_dollenme_tarihi date null,
    dollenme_sayisi integer null,
    tuttu_mu char(1) null
        check (tuttu_mu in ('e', 'h') or tuttu_mu is null), -- e: evet, h: hayir
    son_kuru_tarihi date null,
    son_sut_olcum_tarihi date null,
    created_at timestamp not null default now()
);

create index if not exists ix_master_inek_anne_id
    on suru_karar.master_inek (anne_id);

/*
master_sagim_makine
- Süt ölçüm olaylarıyla ilişki kurulabilmesi için hafif makine tablosu.
